function seededRandom(seed: number) {
  let s = seed;
  return () => {
    s = (s * 9301 + 49297) % 233280;
    return s / 233280;
  };
}

export async function isSeeded() {
  const [{ c }] = await db.select({ c: count() }).from(users);
  return Number(c) > 0;
}

export async function seed() {
  if (await isSeeded()) return { skipped: true };

  // badges
  for (const b of BADGE_DEFS) await db.insert(badges).values(b).onConflictDoNothing();
  const allBadges = await db.select().from(badges);

  // users
  const userIds: Record<string, number> = {};
  for (const u of DEMO_USERS) {
    const [row] = await db
      .insert(users)
      .values({
        email: u.email,
        passwordHash: hashPassword(u.password),
        name: u.name,
        role: u.role,
        avatarColor: u.color,
        xp: u.xp,
        currentStreak: u.streak,
        longestStreak: u.longest,
        lastActiveDate: new Date().toISOString().slice(0, 10),
      })
      .returning({ id: users.id });
    userIds[u.email] = row.id;
  }

  // content
  const allQuestionIds: { id: number; stationId: number; difficulty: number }[] = [];
  const stationOrder: number[] = [];
  let ci = 0;
  for (const c of CONTENT) {
    const [cat] = await db
      .insert(categories)
      .values({ name: c.name, slug: c.slug, color: c.color, icon: c.icon, description: c.description, sortOrder: ci++ })
      .returning({ id: categories.id });
    let ti = 0;
    for (const t of c.topics) {
      const [topic] = await db
        .insert(topics)
        .values({ categoryId: cat.id, title: t.title, description: t.description, sortOrder: ti++ })
        .returning({ id: topics.id });
      let si = 0;
      for (const s of t.stations) {
        const [st] = await db
          .insert(stations)
          .values({ topicId: topic.id, title: s.title, scenario: s.scenario, sortOrder: si++, xpReward: s.xp ?? 50 })
          .returning({ id: stations.id });
        stationOrder.push(st.id);
        let qi = 0;
        for (const q of s.qs) {
          const [qr] = await db
            .insert(questions)
            .values({
              stationId: st.id,
              type: q.t,
              prompt: q.p,
              options: q.o ?? [],
              answer: q.a,
              explanation: q.e,
              difficulty: q.d ?? 1,
              sortOrder: qi++,
            })
            .returning({ id: questions.id });
          allQuestionIds.push({ id: qr.id, stationId: st.id, difficulty: q.d ?? 1 });
        }
      }
    }
  }

  // demo student progress: first 5 stations completed with some mistakes
  const student = userIds["student@nurse.ir"];
  const rnd = seededRandom(42);
  let studentXp = 0;
  const completed = stationOrder.slice(0, 5);
  for (let i = 0; i < completed.length; i++) {
    const sid = completed[i];
    const qs = allQuestionIds.filter((q) => q.stationId === sid);
    const daysAgo = 5 - i;
    const when = new Date(Date.now() - daysAgo * 86400_000 - 3600_000 * 3);
    const [att] = await db
      .insert(attempts)
      .values({ userId: student, stationId: sid, mode: "station", total: qs.length, createdAt: when, finishedAt: when })
      .returning({ id: attempts.id });
    let score = 0;
    let xp = 0;
    for (const q of qs) {
      const correct = rnd() > 0.25;
      if (correct) {
        score++;
        xp += 10 * q.difficulty;
      } else {
        await db.insert(reviewItems).values({ userId: student, questionId: q.id, wrongCount: 1, dueAt: new Date(Date.now() - 3600_000) });
      }
      await db.insert(questionAttempts).values({ userId: student, questionId: q.id, attemptId: att.id, isCorrect: correct, createdAt: when });
    }
    const [stRow] = await db.select().from(stations).where(eq(stations.id, sid));
    const passed = score / qs.length >= 0.7;
    if (passed) xp += stRow.xpReward;
    studentXp += xp;
    await db.update(attempts).set({ score, passed, xpEarned: xp, bestStreak: Math.min(score, 4) }).where(eq(attempts.id, att.id));
    await db.insert(stationProgress).values({ userId: student, stationId: sid, bestScore: score, bestTotal: qs.length, completed: true, attemptsCount: 1, updatedAt: when });
  }
  await db.update(users).set({ xp: studentXp }).where(eq(users.id, student));
  const badgeByKey = new Map(allBadges.map((b) => [b.key, b.id]));
  await db.insert(userBadges).values([
    { userId: student, badgeId: badgeByKey.get("first_step")!, earnedAt: new Date(Date.now() - 5 * 86400_000) },
    { userId: student, badgeId: badgeByKey.get("perfectionist")!, earnedAt: new Date(Date.now() - 2 * 86400_000) },
    { userId: student, badgeId: badgeByKey.get("category_master")!, earnedAt: new Date(Date.now() - 1 * 86400_000) },
  ]);

  // other users: badges & analytics attempts
  const others = DEMO_USERS.filter((u) => u.email !== "student@nurse.ir");
  const rnd2 = seededRandom(7);
  for (const u of others) {
    const uid = userIds[u.email];
    const badgeKeys = ["first_step"];
    if (u.xp > 600) badgeKeys.push("perfectionist");
    if (u.xp > 900) badgeKeys.push("hot_streak", "week_warrior");
    if (u.xp > 1000) badgeKeys.push("xp_1000");
    if (u.xp > 1200) badgeKeys.push("scholar");
    if (u.xp > 2000) badgeKeys.push("ten_stations", "category_master");
    for (const k of badgeKeys) {
      await db.insert(userBadges).values({ userId: uid, badgeId: badgeByKey.get(k)! }).onConflictDoNothing();
    }
    const doneCount = Math.min(stationOrder.length, Math.floor(u.xp / 110));
    for (let i = 0; i < doneCount; i++) {
      const sid = stationOrder[i];
      const qs = allQuestionIds.filter((q) => q.stationId === sid);
      const when = new Date(Date.now() - Math.floor(rnd2() * 20) * 86400_000);
      const [att] = await db
        .insert(attempts)
        .values({ userId: uid, stationId: sid, mode: "station", total: qs.length, createdAt: when, finishedAt: when })
        .returning({ id: attempts.id });
      let score = 0;
      for (const q of qs) {
        // harder questions are answered wrong more often
        const pCorrect = q.difficulty === 3 ? 0.4 : q.difficulty === 2 ? 0.62 : 0.85;
        const correct = rnd2() < pCorrect;
        if (correct) score++;
        await db.insert(questionAttempts).values({ userId: uid, questionId: q.id, attemptId: att.id, isCorrect: correct, createdAt: when });
      }
      await db.update(attempts).set({ score, passed: score / qs.length >= 0.7, xpEarned: score * 10 + 50 }).where(eq(attempts.id, att.id));
      await db.insert(stationProgress).values({ userId: uid, stationId: sid, bestScore: score, bestTotal: qs.length, completed: true, attemptsCount: 1, updatedAt: when });
    }
  }

  return { skipped: false };
}

// CLI entrypoint
if (process.argv[1] && process.argv[1].endsWith("seed.ts")) {
  seed()
    .then((r) => {
      console.log(r.skipped ? "Already seeded" : "Seeded successfully");
      process.exit(0);
    })
    .catch((e) => {
      console.error(e);
      process.exit(1);
    });
}
